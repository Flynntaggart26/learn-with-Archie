export const curriculumMap: Map<string, TopicNode> = new Map(
  curriculumNodes.map((node) => [node.id, node]),
);

export function getTopicById(topicId: string): TopicNode | undefined {
  return curriculumMap.get(topicId);
}

export function getPrerequisites(topicId: string): TopicNode[] {
  const node = curriculumMap.get(topicId);
  if (!node) {
    return [];
  }
  return node.prerequisites
    .map((prereqId) => curriculumMap.get(prereqId))
    .filter((topic): topic is TopicNode => topic !== undefined);
}

export function getDependents(topicId: string): TopicNode[] {
  return curriculumNodes.filter((node) => node.prerequisites.includes(topicId));
}

export function getTopicsByLevel(level: ExamLevel): TopicNode[] {
  return curriculumNodes.filter((node) => node.level === level);
}

export function getTopicsBySubject(subject: SubjectCategory): TopicNode[] {
  return curriculumNodes.filter((node) => node.subject === subject);
}

/**
 * Returns the unique list of subjects that have at least one topic at the
 * given exam level.
 */
export function getSubjectsByLevel(level: ExamLevel): SubjectCategory[] {
  const subjects = new Set<SubjectCategory>();
  for (const node of curriculumNodes) {
    if (node.level === level) {
      subjects.add(node.subject);
    }
  }
  return Array.from(subjects);
}

/**
 * Returns the top-level (parent) topics for a given subject at a given level.
 * A top-level topic is one that is not listed as a subtopic of any other node.
 */
export function getTopLevelTopics(
  subject: SubjectCategory,
  level: ExamLevel,
): TopicNode[] {
  const allSubtopicIds = new Set<string>();
  for (const node of curriculumNodes) {
    if (node.subtopics) {
      for (const sub of node.subtopics) {
        allSubtopicIds.add(sub.id);
      }
    }
  }

  return curriculumNodes.filter(
    (node) =>
      node.subject === subject &&
      node.level === level &&
      !allSubtopicIds.has(node.id),
  );
}

/**
 * Returns the subtopics for a given topic node.
 */
export function getSubtopics(topicId: string): TopicNode[] {
  const node = curriculumMap.get(topicId);
  if (!node || !node.subtopics) {
    return [];
  }
  return node.subtopics;
}
